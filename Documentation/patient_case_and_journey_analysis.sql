## Patient Case-wise Event Count and Journey Analysis

**Objective**

To analyse patient-level event distribution and individual patient journeys in the CareFlow dataset using BigQuery SQL.

**Work Completed**

- Calculated event counts for each patient case using `COUNT(*)` and `GROUP BY`.
- Retrieved the first 10 patient cases to review event distribution.
- Selected an individual case to examine its complete event sequence.
- Analysed event IDs, event order, activities, timestamps, and department details.
- Reviewed chronological activity progression and loop-back information where available.

**Key Observations**

- Identified event distribution across individual patient cases.
- Examined the sequence of clinical activities within patient journeys.
- Used event order and timestamps to understand pathway progression.

**Outcome**

Completed patient case-wise event count and individual journey analysis, providing insights into patient activity distribution and clinical pathway patterns.
